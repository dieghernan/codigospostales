# Generate the citation sections from CITATION.cff: ruby scripts/citation.rb
require "yaml"
require "date"

root = File.expand_path("..", __dir__)
citation = YAML.safe_load_file(File.join(root, "CITATION.cff"), permitted_classes: [Date])
                 .fetch("preferred-citation")
authors = citation.fetch("authors")
names = authors.map do |author|
  initials = author.fetch("given-names").split.map { |name| "#{name[0]}." }.join(" ")
  "#{author.fetch('family-names')}, #{initials}"
end.join("; ")
bib_authors = authors.map do |author|
  "#{author.fetch('family-names')}, #{author.fetch('given-names')}"
end.join(" and ")
block = <<~MARKDOWN
  <!-- citation:start; generated by scripts/citation.rb -->
  ## Cómo citar

  Si utilizas estos datos, cita el proyecto de la siguiente forma:

  > #{names} (#{citation.fetch('year')}). *#{citation.fetch('title')}*
  > (versión #{citation.fetch('version')}) [Conjunto de datos].
  > https://doi.org/#{citation.fetch('doi')}

  <details markdown="1">
  <summary>Referencia en BibTeX</summary>

  ```bibtex
  @misc{hernangomez_codigos_postales,
    author = {#{bib_authors}},
    title = {#{citation.fetch('title')}},
    year = {#{citation.fetch('year')}},
    version = {#{citation.fetch('version')}},
    doi = {#{citation.fetch('doi')}},
    url = {#{citation.fetch('url')}},
    note = {Conjunto de datos}
  }
  ```

  </details>
  <!-- citation:end -->
MARKDOWN

targets = { "README.md" => "## Generación", "docs/index.md" => "## Uso de inteligencia artificial" }
targets.each do |file, heading|
  path = File.join(root, file)
  original = File.read(path, encoding: "UTF-8").gsub("\r\n", "\n")
  updated = if original.include?("<!-- citation:start;")
    original.sub(/<!-- citation:start;.*?<!-- citation:end -->\n/m, block)
  else
    raise "Missing heading in #{file}: #{heading}" unless original.include?(heading)
    original.sub(heading, "#{block}\n#{heading}")
  end
  if ARGV.include?("--check")
    abort "Citation is outdated in #{file}. Run ruby scripts/citation.rb" unless updated == original
  else
    File.write(path, updated, encoding: "UTF-8")
  end
end
